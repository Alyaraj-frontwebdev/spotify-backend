const mongoose = require("mongoose");

const userShema = new mongoose.Schema({
    username: {
        type: String,
        unique: true,
        required: true
    },
    email: {
        type: String,
        unique: true,
        required: true
    },
    password: {
        type: String,
        required: true
    },
    role: {
        type: String,
        enum: ['user', 'artist'],
        default: 'user'
    }
});




const userModel = mongoose.model("user", userShema);

module.exports = userModel;